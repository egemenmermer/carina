let current: Strings = en;
export let lang: 'en' | 'tr' = 'en';

export function initLanguage(): void {
  const pref = store.settings().lang;
  lang = pref === 'auto' ? (tvLanguage().indexOf('tr') === 0 ? 'tr' : 'en') : pref;
  current = lang === 'tr' ? tr : en;
  document.documentElement.lang = lang;
}

export function t(key: StringKey, args?: Record<string, string | number>): string {
  let s = current[key] || en[key] || key;
  if (args) for (const k of Object.keys(args)) s = s.split('{' + k + '}').join(String(args[k]));
  return s;
}
